function paintGrid(ctx, ox, oy, size, def) {
  const rows = def.grid.length;
  const cols = def.grid[0].length;
  const u = size / cols;
  const eps = 0.04;
  for (let y = 0; y < rows; y++) {
    const row = def.grid[y];
    for (let x = 0; x < cols; x++) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') continue;
      const fill = def.pal[ch];
      if (!fill) continue;
      ctx.fillStyle = fill;
      ctx.fillRect(ox + x * u, oy + y * u, u + eps, u + eps);
    }
  }
}

export function drawDetailedItemSprite(ctx, ox, oy, size, key) {
  const def = DETAILED_ITEM_DEFS[key];
  if (!def) return false;
  paintGrid(ctx, ox, oy, size, def);
  return true;
}
