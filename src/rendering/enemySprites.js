export function drawEnemyBackdrop(ctx, x, y, s, key) {
  const color = ENEMY_AURA[key] || '#503858';
  ctx.save();
  ctx.globalAlpha = 0.22;
  const cx = x + s / 2;
  const cy = y + s * 0.58;
  const g = ctx.createRadialGradient(cx, cy, s * 0.06, cx, cy, s * 0.5);
  g.addColorStop(0, color);
  g.addColorStop(0.65, color + '44');
  g.addColorStop(1, 'transparent');
  ctx.fillStyle = g;
  ctx.fillRect(x, y, s, s);
  ctx.restore();
}

export function drawEnemyPolish(ctx, x, y, s) {
  const u = s / 32;
  ctx.save();
  ctx.globalAlpha = 0.35;
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(x, y, s, u);
  ctx.fillRect(x, y, u, s * 0.35);
  ctx.globalAlpha = 0.2;
  ctx.fillRect(x + s - u, y, u, s * 0.25);
  ctx.restore();
}

